test('quote is encoded safely and omits absent optional data', () => {
  const message = quoteMessage({ name: ' Prueba & QA ', phone: '+00 00000000', vehicle: '', description: '' }, 'Personalización automotriz');
  assert.ok(message.includes('Nombre: Prueba & QA'));
  assert.ok(!message.includes('Vehículo:'));
  const url = new URL(whatsappUrl('000000000000', message));
  assert.equal(url.searchParams.get('text'), message);
  assert.equal(whatsappUrl(null, message), null);
  assert.equal(whatsappUrl('invalid', message), null);
  assert.equal(safeUrl('javascript:alert(1)'), null);
  assert.equal(escapeHtml('<script>'), '&lt;script&gt;');
});
