import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile, readdir, stat } from 'node:fs/promises';
import { quoteMessage, whatsappUrl, safeUrl, escapeHtml } from '../src/lib.mjs';
import { GET as robots } from '../src/pages/robots.txt.js';
import { GET as sitemap } from '../src/pages/sitemap.xml.js';
const html = await readFile(new URL('../dist/index.html', import.meta.url), 'utf8');

test('production HTML contains every section and resolves all anchors before JavaScript', () => {
  assert.equal((html.match(/<h1[\s>]/g) ?? []).length, 1);
  const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(match => match[1]);
  assert.equal(ids.length, new Set(ids).size);
  for (const [, anchor] of html.matchAll(/href="#([^"]+)"/g)) assert.ok(ids.includes(anchor), anchor);
  for (const id of ['inicio', 'servicios', 'resultados', 'cotizacion', 'sucursales', 'contacto']) assert.ok(ids.includes(id));
  assert.ok(html.includes('Personalización automotriz'));
  assert.ok(html.includes('id="quote-form"'));
});
test('static output has one HTML page and no server runtime or hydration', async () => {
  const files = await readdir(new URL('../dist/', import.meta.url), { recursive: true });
  assert.deepEqual(files.filter(file => file.endsWith('.html')), ['index.html']);
  assert.ok(!files.includes('server'));
  assert.ok(!html.includes('astro-island'));
  const scripts = files.filter(file => file.endsWith('.js'));
  const inline = [...html.matchAll(/<script type="module">([\s\S]*?)<\/script>/g)];
  assert.equal(scripts.length + inline.length, 1, 'Only the existing menu/form/motion script is bundled or inlined');
  const size = inline.length ? Buffer.byteLength(inline[0][1]) : (await stat(new URL(`../dist/${scripts[0]}`, import.meta.url))).size;
  assert.ok(size < 8000, `Client bundle must remain small (${size} bytes)`);
});
